"""
============================================
ПОДКЛЮЧЕНИЕ К БАЗЕ ДАННЫХ
============================================
Мы используем SQLAlchemy — это ORM (Object-Relational Mapping).
ORM позволяет работать с базой данных через Python-объекты
вместо написания SQL-запросов вручную.

Например вместо:
    INSERT INTO users (device_id) VALUES ('abc123')

Мы пишем:
    user = User(device_id='abc123')
    db.add(user)
    db.commit()

Это удобнее, безопаснее и меньше ошибок.
"""

from sqlalchemy import create_engine
from sqlalchemy.ext.declarative import declarative_base
from sqlalchemy.orm import sessionmaker
from app.config import DATABASE_URL

# ============================================
# СОЗДАЁМ ДВИЖОК БАЗЫ ДАННЫХ
# ============================================
# Engine — это "мотор" который умеет общаться с SQLite.
# connect_args={"check_same_thread": False} нужен потому что
# SQLite по умолчанию работает только в одном потоке,
# а FastAPI работает в нескольких потоках одновременно.

engine = create_engine(
    DATABASE_URL,
    connect_args={"check_same_thread": False}
)

# ============================================
# СОЗДАЁМ ФАБРИКУ СЕССИЙ
# ============================================
# Сессия — это "разговор" с базой данных.
# Открыли сессию → сделали запросы → закрыли сессию.
#
# autocommit=False — мы сами решаем когда сохранять данные
# autoflush=False — данные не сохраняются автоматически

SessionLocal = sessionmaker(
    autocommit=False,
    autoflush=False,
    bind=engine
)

# ============================================
# БАЗОВЫЙ КЛАСС ДЛЯ МОДЕЛЕЙ
# ============================================
# Все наши модели (User, Payment, PromoCode)
# будут наследоваться от этого класса.
# Он даёт им способность "знать" о базе данных.

Base = declarative_base()


# ============================================
# ФУНКЦИЯ ДЛЯ ПОЛУЧЕНИЯ СЕССИИ
# ============================================
# Эту функцию мы будем вызывать в каждом API-эндпоинте.
# Она открывает соединение с базой, отдаёт его,
# и после завершения запроса — закрывает.
#
# yield — это как return, но "с паузой".
# Код до yield выполняется ДО обработки запроса.
# Код после yield (в finally) выполняется ПОСЛЕ.

def get_db():
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()